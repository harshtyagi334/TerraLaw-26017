import * as XLSX from 'xlsx';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { LandProject, UserRole } from '../types';

export interface ReportFilterMetadata {
  state?: string;
  district?: string;
  projectType?: string;
  stage?: string;
  risk?: string;
  searchQuery?: string;
  userRole?: UserRole;
  officerName?: string;
  officerDesignation?: string;
  notes?: string;
}

/**
 * Generate a unique formal document reference number
 */
export function generateDocRef(prefix: string = 'DoLR-NLADSS'): string {
  const dateStr = new Date().toISOString().slice(0, 10).replace(/-/g, '');
  const randomSuffix = Math.floor(1000 + Math.random() * 9000);
  return `${prefix}/REP/${dateStr}/${randomSuffix}`;
}

/**
 * Format currency in Indian Crores (₹ Cr)
 */
function formatCr(val: number | undefined | null): string {
  if (val === undefined || val === null) return '₹0.00 Cr';
  return `₹${val.toFixed(2)} Cr`;
}

