// 2. PROJECT LIST PDF EXPORT (.PDF)
// ==========================================
export function exportProjectListToPDF(
  projects: LandProject[],
  metadata: ReportFilterMetadata = {},
  fileNamePrefix: string = 'DoLR_Project_Status_Report'
): void {
  // Create landscape document for tabular breadth
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'pt',
    format: 'a4',
  });

  const docRef = generateDocRef('DoLR-PLIST');
  const timestamp = new Date().toLocaleString('en-IN', {
    dateStyle: 'medium',
    timeStyle: 'short',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Primary Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 56, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text('GOVERNMENT OF INDIA • MINISTRY OF RURAL DEVELOPMENT', 30, 24);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225); // slate-300
  doc.text(
    'DEPARTMENT OF LAND RESOURCES (DoLR) | NATIONAL LAND ACQUISITION DELAY SURVEILLANCE SYSTEM',
    30,
    38
  );

  doc.setTextColor(251, 191, 36); // amber-400
  doc.setFont('helvetica', 'bold');
  doc.text('FORMAL STATUS REPORT', pageWidth - 30, 24, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(226, 232, 240);
  doc.text(`Ref: ${docRef}`, pageWidth - 30, 38, { align: 'right' });

  // Sub-header & Report Title
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('Statutory Land Acquisition Projects Status & Delay Risk Register', 30, 80);

  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text(
    `Audited under RFCTLARR Act, 2013 and ML Early Warning Predictive Engine • Generated: ${timestamp}`,
    30,
    94
  );

  // Metadata Panel / Summary Boxes
  doc.setFillColor(248, 250, 252); // slate-50
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.roundedRect(30, 104, pageWidth - 60, 48, 4, 4, 'FD');

  const highRiskCount = projects.filter((p) => (p.prediction?.risk_score ?? 0) >= 65).length;
  const ongoingCount = projects.filter((p) => p.project_status === 'Ongoing').length;
  const totalAssessed = projects.reduce((acc, p) => acc + (p.compensation?.total_compensation_assessed_cr || 0), 0);
  const totalDisbursed = projects.reduce((acc, p) => acc + (p.compensation?.total_compensation_disbursed_cr || 0), 0);
  const avgDelay = ongoingCount > 0
    ? Math.round(
        projects
          .filter((p) => p.project_status === 'Ongoing')
          .reduce((acc, p) => acc + (p.prediction?.predicted_delay_days || 0), 0) / ongoingCount
      )
    : 0;

  // Box 1: Total Projects
  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.text('TOTAL AUDITED', 45, 120);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text(`${projects.length} Packages`, 45, 136);

  // Box 2: High Risk
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(185, 28, 28);
  doc.text('HIGH RISK (RED ALERT)', 170, 120);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(220, 38, 38);
  doc.text(`${highRiskCount} (${((highRiskCount / Math.max(1, projects.length)) * 100).toFixed(0)}%)`, 170, 136);

  // Box 3: Avg Predicted Slippage
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text('AVG PREDICTED SLIPPAGE', 315, 120);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text(`+${avgDelay} Days`, 315, 136);

  // Box 4: Compensation DBT Progress
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text('COMPENSATION DBT', 475, 120);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  const dbtPct = totalAssessed > 0 ? ((totalDisbursed / totalAssessed) * 100).toFixed(0) : '0';
  doc.text(`${dbtPct}% (${formatCr(totalDisbursed)})`, 475, 136);

  // Box 5: Filter Scope
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text('APPLIED SCOPE & ROLE', 645, 120);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  const scopeTxt = `${metadata.state || 'All States'} / ${metadata.district || 'All Districts'}`;
  doc.text(scopeTxt.length > 25 ? scopeTxt.substring(0, 24) + '...' : scopeTxt, 645, 134);
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);
  doc.text(`Role: ${metadata.userRole || 'Officer'}`, 645, 144);

  // Build Table Data
  const tableHead = [
    [
      'ID',
      'Project Title & Location',
      'Sector',
      'Stage',
      'Land (Ha)',
      'Comp. DBT %',
      'Poss. %',
      'Risk Score',
      'Category',
      'Delay (Days)',
      'Primary Delay Driver / Recommendation',
    ],
  ];

  const tableBody = projects.map((p) => {
    const assessed = p.compensation?.total_compensation_assessed_cr || 0;
    const disbursed = p.compensation?.total_compensation_disbursed_cr || 0;
    const compPct = assessed > 0 ? `${Math.round((disbursed / assessed) * 100)}%` : '0%';
    const possPct = `${p.possession?.possession_percentage || 0}%`;
    const riskScore = p.prediction?.risk_score ?? 0;
    const riskCat = p.prediction?.risk_category ?? 'Low';
    const delayDays = p.project_status === 'Completed'
      ? `${p.actual_delay_days ?? 0} (Act)`
      : `+${p.prediction?.predicted_delay_days ?? 0}`;
    const keyDriver = p.prediction?.top_shap_factors?.[0]?.factor || 'Clearances SLA compliance';
    const recAction = p.prediction?.recommendations?.[0]?.action || 'Routine stage tracking';

    return [
      p.project_id,
      `${p.project_name}\n[${p.district}, ${p.state}]`,
      p.project_type,
      p.current_stage,
      `${p.land_area_hectares} Ha`,
      compPct,
      possPct,
      `${riskScore}/100`,
      riskCat,
      delayDays,
      `${keyDriver} • ${recAction}`,
    ];
  });

  autoTable(doc, {
    head: tableHead,
    body: tableBody,
    startY: 162,
    margin: { left: 30, right: 30, bottom: 40 },
    theme: 'striped',
    styles: {
      fontSize: 7.5,
      cellPadding: 4,
      textColor: [30, 41, 59],
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: [30, 41, 59], // slate-800
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 7.5,
      halign: 'left',
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 50, fontStyle: 'bold' },
      1: { cellWidth: 140 },
      2: { cellWidth: 55 },
      3: { cellWidth: 60 },
      4: { cellWidth: 50, halign: 'right' },
      5: { cellWidth: 55, halign: 'right' },
      6: { cellWidth: 45, halign: 'right' },
      7: { cellWidth: 50, halign: 'center', fontStyle: 'bold' },
      8: { cellWidth: 50, halign: 'center' },
      9: { cellWidth: 60, halign: 'right', fontStyle: 'bold' },
      10: { cellWidth: 165 },
    },
    didParseCell: (data) => {
      // Colorize Risk Category and Score
      if (data.section === 'body') {
        const rawRow = projects[data.row.index];
        const riskScore = rawRow?.prediction?.risk_score ?? 0;
        if (data.column.index === 7 || data.column.index === 8) {
          if (riskScore >= 65) {
            data.cell.styles.textColor = [185, 28, 28]; // red-700
            data.cell.styles.fontStyle = 'bold';
          } else if (riskScore >= 35) {
            data.cell.styles.textColor = [180, 83, 9]; // amber-700
            data.cell.styles.fontStyle = 'bold';
          } else {
            data.cell.styles.textColor = [21, 128, 61]; // green-700
          }
        }
      }
    },
    didDrawPage: (data) => {
      // Footer on each page
      const pageNumber = (doc as any).internal.getNumberOfPages();
      doc.setFontSize(7.5);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(148, 163, 184); // slate-400

      doc.setDrawColor(226, 232, 240);
      doc.line(30, pageHeight - 26, pageWidth - 30, pageHeight - 26);

      doc.text(
        'Department of Land Resources (DoLR) • Ministry of Rural Development • CONFIDENTIAL & OFFICIAL USE ONLY',
        30,
        pageHeight - 14
      );
      doc.text(
        `Page ${data.pageNumber} of ${pageNumber}`,
        pageWidth - 30,
        pageHeight - 14,
        { align: 'right' }
      );
    },
  });

  const dateTag = new Date().toISOString().slice(0, 10);
  doc.save(`${fileNamePrefix}_${dateTag}.pdf`);
}

